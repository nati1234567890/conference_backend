const PDFDocument = require("pdfkit");

const exportRegistrationsToPdf = (registrations) => {
  return new Promise((resolve, reject) => {
    try {
      const doc = new PDFDocument({ size: "A4", margin: 40 });
      const chunks = [];

      doc.on("data", (chunk) => chunks.push(chunk));
      doc.on("end", () => resolve(Buffer.concat(chunks)));
      doc.on("error", reject);

      // ---- Header band ----
      doc.rect(0, 0, doc.page.width, 100).fill("#0B1E3D");
      doc
        .fillColor("#FFFFFF")
        .fontSize(20)
        .font("Helvetica-Bold")
        .text("Ethio Bridge Investment Conference 2026", 40, 30);
      doc
        .fillColor("#C9A34A")
        .fontSize(12)
        .font("Helvetica")
        .text("Invest • Trade • Partner • Grow", 40, 58);
      doc.fillColor("#FFFFFF").fontSize(10).text("Registration Report", 40, 76);

      // Report meta
      doc
        .fillColor("#6B7280")
        .fontSize(9)
        .font("Helvetica")
        .text(
          `Generated: ${new Date().toISOString().replace("T", " ").slice(0, 19)}`,
          40,
          110,
        );
      doc.text(`Total participants: ${registrations.length}`, 40, 124);

      let y = 150;

      // Table headers
      const colX = {
        no: 40,
        name: 70,
        company: 220,
        category: 360,
        status: 470,
        checked: 530,
      };

      doc.fillColor("#0B1E3D").fontSize(10).font("Helvetica-Bold");
      doc.text("#", colX.no, y);
      doc.text("Name", colX.name, y);
      doc.text("Company", colX.company, y);
      doc.text("Category", colX.category, y);
      doc.text("Status", colX.status, y);
      doc.text("Checked", colX.checked, y);

      y += 14;
      doc
        .moveTo(40, y)
        .lineTo(doc.page.width - 40, y)
        .strokeColor("#E5E7EB")
        .lineWidth(1)
        .stroke();
      y += 8;

      // Rows
      doc.font("Helvetica").fontSize(9).fillColor("#1A1A1A");

      registrations.forEach((r, i) => {
        // Page break check
        if (y > doc.page.height - 60) {
          doc.addPage();
          y = 40;
        }

        doc.fillColor("#6B7280").text(String(i + 1), colX.no, y);
        doc
          .fillColor("#1A1A1A")
          .text(r.fullName || "-", colX.name, y, { width: 145 });
        doc
          .fillColor("#6B7280")
          .text(r.company || "-", colX.company, y, { width: 135 });
        doc
          .fillColor("#1A1A1A")
          .text(r.registrationCategory || "-", colX.category, y, {
            width: 105,
          });
        doc
          .fillColor("#6B7280")
          .text(r.status || "-", colX.status, y, { width: 55 });
        doc
          .fillColor(r.checkedIn ? "#059669" : "#9CA3AF")
          .text(r.checkedIn ? "Yes" : "No", colX.checked, y);

        y += 18;

        // Divider
        doc
          .moveTo(40, y - 4)
          .lineTo(doc.page.width - 40, y - 4)
          .strokeColor("#F3F4F6")
          .stroke();
      });

      // Footer on last page
      doc
        .fillColor("#9CA3AF")
        .fontSize(8)
        .text(
          `© ${new Date().getFullYear()} Ethio Bridge Global Services PLC — Generated by Conference Backend`,
          40,
          doc.page.height - 30,
          { align: "center", width: doc.page.width - 80 },
        );

      doc.end();
    } catch (err) {
      reject(err);
    }
  });
};

module.exports = exportRegistrationsToPdf;
